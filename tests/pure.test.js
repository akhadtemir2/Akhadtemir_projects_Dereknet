/**
 * Локальные тесты чистой логики Dereknet CLM.
 *
 * Запуск:  node tests/pure.test.js
 *
 * Apps Script нельзя протестировать локально целиком (нет Drive/Docs/Sheets),
 * поэтому вся логика, которая может ошибиться молча — контрольная сумма БИН,
 * поиск незаполненных плейсхолдеров, согласование падежей, имена файлов —
 * вынесена в src/03_Pure.gs и проверяется здесь ДО заливки в Google.
 */
'use strict';

const path = require('path');
const Module = require('module');

// Позволяем require() читать .gs как обычный JavaScript
Module._extensions['.gs'] = Module._extensions['.js'];
const P = require(path.join(__dirname, '..', 'src', '03_Pure.gs'));

let passed = 0;
let failed = 0;
const failures = [];

function check(name, actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) {
    passed++;
  } else {
    failed++;
    failures.push(`  ✗ ${name}\n      получено:  ${a}\n      ожидалось: ${e}`);
  }
}

function group(title) {
  console.log('\n' + title);
}

// ═══════════════════════════════════════════════════════════════════════
group('БИН — контрольная сумма');
// ═══════════════════════════════════════════════════════════════════════
// Реальные БИН из истории проекта — контрольный разряд должен сойтись.
check('БИН Dereknet 190440019884',        P.isValidKzBin_('190440019884'), true);
check('БИН из тестов 220140027733',       P.isValidKzBin_('220140027733'), true);
check('БИН из тестов 090740019001',       P.isValidKzBin_('090740019001'), true);

// Одна перепутанная цифра — типичная ошибка распознавания — должна отлавливаться.
check('опечатка в последней цифре',       P.isValidKzBin_('190440019885'), false);
check('перепутаны 8 и 3 в середине',      P.isValidKzBin_('190440013884'), false);
check('11 цифр вместо 12',                P.isValidKzBin_('19044001988'),  false);
check('13 цифр',                          P.isValidKzBin_('1904400198840'), false);
check('буквы внутри',                     P.isValidKzBin_('19044001988A'), false);
check('пустая строка',                    P.isValidKzBin_(''),             false);
check('null',                             P.isValidKzBin_(null),           false);
check('БИН с пробелами и дефисами',       P.isValidKzBin_('1904-4001 9884'), true);

group('БИН — расшифровка структуры');
check('Dereknet = резидент, головная',    P.describeKzBin_('190440019884'), 'юр. лицо-резидент, головная организация');
check('несуществующий месяц 99',          P.describeKzBin_('199940019884'), '');

group('БИН — нормализация ведущих нулей');
check('потерянный ведущий ноль',          P.normalizeBin_('90740019001'),   '090740019001');
check('уже 12 цифр — без изменений',      P.normalizeBin_('190440019884'),  '190440019884');
check('мусор вокруг цифр',                P.normalizeBin_('БИН: 190440019884.'), '190440019884');
check('слишком коротко — не дополняем',   P.normalizeBin_('1234'),          '1234');

// ═══════════════════════════════════════════════════════════════════════
group('Плейсхолдеры');
// ═══════════════════════════════════════════════════════════════════════
check('находит все токены',
  P.extractTokens_('Договор {{AGREEMENT_NUMBER}} от {{DATE_DAY}} {{DATE_MONTH_RU}}'),
  ['AGREEMENT_NUMBER', 'DATE_DAY', 'DATE_MONTH_RU']);
check('убирает дубликаты',
  P.extractTokens_('{{A}} текст {{A}} ещё {{B}}'), ['A', 'B']);
check('терпит пробелы внутри скобок',
  P.extractTokens_('{{ SPACED }}'), ['SPACED']);
check('нет токенов — пустой массив',
  P.extractTokens_('обычный текст без плейсхолдеров'), []);
check('игнорирует одиночные скобки',
  P.extractTokens_('{NOT_A_TOKEN} и {{REAL}}'), ['REAL']);
check('все обязательные KZ-токены есть в словаре известных',
  P.REQUIRED_KZ_TOKENS.filter(t => P.KNOWN_TOKENS.indexOf(t) === -1), []);

// ═══════════════════════════════════════════════════════════════════════
group('Правовые формы и согласование падежей');
// ═══════════════════════════════════════════════════════════════════════
check('ТОО → товарищество',   P.inferLegalFormRu_('ТОО «Арена S»'), 'товарищество с ограниченной ответственностью');
check('АО → акционерное',     P.inferLegalFormRu_('АО «Казпочта»'), 'акционерное общество');
check('ИП → предприниматель', P.inferLegalFormRu_('ИП Иванов И.И.'), 'индивидуальный предприниматель');
check('LLC → компания',       P.inferLegalFormRu_('Acme LLC'),      'компания с ограниченной ответственностью');
check('неизвестное → юр.лицо',P.inferLegalFormRu_('Нечто странное'),'юридическое лицо');

check('EN: ТОО → LLP',        P.inferLegalFormEn_('ТОО «Арена S»'), 'a limited liability partnership');
check('EN: Inc → corporation',P.inferLegalFormEn_('Acme Inc'),      'a corporation');

// Регрессия: в JS `\b` не работает с кириллицей — эти проверки фиксируют исправление.
check('регрессия: ТОО с кавычкой-ёлочкой', P.inferLegalFormRu_('ТОО«БезПробела»'), 'товарищество с ограниченной ответственностью');
check('регрессия: ТОО в конце строки',     P.inferLegalFormRu_('ТОО'),             'товарищество с ограниченной ответственностью');
check('регрессия: ТООО ≠ ТОО',             P.inferLegalFormRu_('ТООО Странное'),   'юридическое лицо');
check('регрессия: ИПОТЕКА ≠ ИП',           P.inferLegalFormRu_('ИПОТЕКА Банк'),    'юридическое лицо');
check('регрессия: АО с точкой',            P.inferLegalFormRu_('АО. Казпочта'),    'акционерное общество');
check('регрессия: строчными буквами',      P.inferLegalFormRu_('тоо «арена»'),     'товарищество с ограниченной ответственностью');
check('регрессия: пробел в начале',        P.inferLegalFormRu_('  ТОО «Арена»'),   'товарищество с ограниченной ответственностью');
check('регрессия: LLC внутри слова',       P.inferLegalFormRu_('BALLCORP Group'),  'юридическое лицо');

// Ключевой грамматический баг v4.x: «ТОО ... зарегистрированная» вместо «зарегистрированное»
check('ТОО → зарегистрированное', P.inferRegAgreementRu_('ТОО «Арена S»'), 'зарегистрированное');
check('АО → зарегистрированное',  P.inferRegAgreementRu_('АО «Казпочта»'), 'зарегистрированное');
check('ИП → зарегистрированный',  P.inferRegAgreementRu_('ИП Иванов'),     'зарегистрированный');
check('LLC → зарегистрированная', P.inferRegAgreementRu_('Acme LLC'),      'зарегистрированная');

// Преамбула «в лице …» требует родительного падежа
check('должность в род. падеже (ТОО)', P.inferRepPositionRu_('ТОО «Арена S»'), 'Директора');
check('должность в род. падеже (АО)',  P.inferRepPositionRu_('АО «Казпочта»'), 'Председателя Правления');
check('должность в род. падеже (ИП)',  P.inferRepPositionRu_('ИП Иванов'),     'Индивидуального предпринимателя');

// ═══════════════════════════════════════════════════════════════════════
group('Транслитерация');
// ═══════════════════════════════════════════════════════════════════════
check('русский адрес',      P.transliterateRuToEn_('ул. Сатпаева 23А'), 'ul. Satpaeva 23A');
check('ФИО с заглавных',    P.transliterateRuToEn_('Кабдулов Саламат'), 'Kabdulov Salamat');
check('казахские буквы',    P.transliterateRuToEn_('Қазақстан'),        'Qazaqstan');
check('мягкий знак исчезает',P.transliterateRuToEn_('Апрель'),          'Aprel');
check('латиница не трогается',P.transliterateRuToEn_('Acme LLC'),       'Acme LLC');

// ═══════════════════════════════════════════════════════════════════════
group('Имена файлов');
// ═══════════════════════════════════════════════════════════════════════
// Баг v4.x: регулярка вырезала казахские буквы → «ТОО Қазақстан» → «ТОО азастан»
check('казахские буквы сохраняются', P.safeFileName_('ТОО Қазақстан Мұнай'), 'ТОО_Қазақстан_Мұнай');
check('кавычки и слэши убираются',   P.safeFileName_('ТОО «Арена S» / филиал'), 'ТОО_Арена_S_филиал');
check('обрезка по длине',            P.safeFileName_('А'.repeat(60), 10).length, 10);
check('пустое имя → partner',        P.safeFileName_(''), 'partner');
check('только спецсимволы → partner',P.safeFileName_('«»/\\:*?'), 'partner');

// ═══════════════════════════════════════════════════════════════════════
group('Очистка данных из реестров');
// ═══════════════════════════════════════════════════════════════════════
// Реальный случай: договор с АО «Народный банк» уехал с текстом
// «АО &quot;НАРОДНЫЙ БАНК КАЗАХСТАНА&quot;» — источник отдаёт двойное кодирование.
check('двойное кодирование &amp;quot;',
  P.decodeHtmlEntities_('АО &amp;quot;НАРОДНЫЙ БАНК&amp;quot;'), 'АО "НАРОДНЫЙ БАНК"');
check('обычное &quot;',        P.decodeHtmlEntities_('АО &quot;Банк&quot;'), 'АО "Банк"');
check('числовая сущность',     P.decodeHtmlEntities_('&#171;Банк&#187;'), '«Банк»');
check('шестнадцатеричная',     P.decodeHtmlEntities_('&#x41;&#x42;'), 'AB');
check('ёлочки по имени',       P.decodeHtmlEntities_('&laquo;Банк&raquo;'), '«Банк»');
check('амперсанд в названии',  P.decodeHtmlEntities_('Procter &amp; Gamble'), 'Procter & Gamble');
check('без сущностей — как есть', P.decodeHtmlEntities_('ТОО «Арена S»'), 'ТОО «Арена S»');

// Реальный случай: в поле «Адрес» уехало соседнее предложение из реестра.
check('обрезка хвоста «Руководитель …»',
  P.cleanAddress_('компании: A26M3K5, ГОРОД АЛМАТЫ, ПР. АЛЬ-ФАРАБИ, Д. 40. Руководитель АО «Банк» – ИВАНОВ И.И.'),
  'A26M3K5, ГОРОД АЛМАТЫ, ПР. АЛЬ-ФАРАБИ, Д. 40');
check('срезает префикс «компании:»',
  P.cleanAddress_('компании: 060016, г. Атырау, ул. Сатпаева 23А'),
  '060016, г. Атырау, ул. Сатпаева 23А');
check('обрезка по «Проверено»',
  P.cleanAddress_('050000, г. Алматы, ул. Абая, 10 Проверено 01.01.2026'),
  '050000, г. Алматы, ул. Абая, 10');
check('нормальный адрес не трогает',
  P.cleanAddress_('060016, Республика Казахстан, г. Атырау, ул. Сатпаева 23А'),
  '060016, Республика Казахстан, г. Атырау, ул. Сатпаева 23А');
check('схлопывает пробелы',   P.cleanAddress_('  г.   Алматы,   ул. Абая 10  '), 'г. Алматы, ул. Абая 10');
check('мусор длиннее 250 → пусто', P.cleanAddress_('г. Алматы, ' + 'ул. Длинная 1, '.repeat(30)), '');
check('остался «Руководитель» → пусто',
  P.cleanAddress_('Руководитель ИВАНОВ ИВАН, г. Алматы'), '');
check('пустой вход',          P.cleanAddress_(''), '');

check('кавычки → ёлочки',     P.normalizeCompanyName_('АО "Народный банк"'), 'АО «Народный банк»');
check('ёлочки не трогает',    P.normalizeCompanyName_('ТОО «Арена S»'),      'ТОО «Арена S»');
check('одинарные кавычки',    P.normalizeCompanyName_("ТОО 'Арена'"),        'ТОО «Арена»');
check('лишние пробелы',       P.normalizeCompanyName_('ТОО   «Арена   S»'),  'ТОО «Арена S»');
check('без кавычек — как есть',P.normalizeCompanyName_('Acme Inc'),          'Acme Inc');

// ═══════════════════════════════════════════════════════════════════════
group('Разбор JSON от модели');
// ═══════════════════════════════════════════════════════════════════════
check('чистый JSON',        P.parseJsonLoose_('{"a":1}'), { a: 1 });
check('в markdown-обёртке', P.parseJsonLoose_('```json\n{"a":1}\n```'), { a: 1 });
check('с болтовнёй вокруг', P.parseJsonLoose_('Вот результат: {"a":1} готово'), { a: 1 });
try {
  P.parseJsonLoose_('никакого json тут нет');
  check('без JSON → исключение', 'не бросил', 'исключение');
} catch (e) {
  check('без JSON → исключение', 'исключение', 'исключение');
}

// ═══════════════════════════════════════════════════════════════════════
group('Понятные пользователю ошибки');
// ═══════════════════════════════════════════════════════════════════════
check('каждая ошибка содержит «Что делать»',
  Object.keys(P.ERROR_HELP).filter(c => P.humanizeError_(c, '').indexOf('Что делать:') === -1), []);
check('неизвестный код тоже даёт инструкцию',
  P.humanizeError_('НЕВЕДОМАЯ_ХРЕНЬ', 'stack trace').indexOf('Что делать:') !== -1, true);
check('риск контрагента предупреждает явно',
  P.humanizeError_('РИСК_КОНТРАГЕНТА', '').indexOf('СТОП') !== -1, true);

// ═══════════════════════════════════════════════════════════════════════
console.log('\n' + '─'.repeat(60));
if (failed) {
  console.log(failures.join('\n'));
  console.log('─'.repeat(60));
}
console.log(`Пройдено: ${passed}   Провалено: ${failed}`);
process.exit(failed ? 1 : 0);
